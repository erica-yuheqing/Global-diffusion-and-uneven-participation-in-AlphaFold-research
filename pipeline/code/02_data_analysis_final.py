import marimo

__generated_with = "0.23.1"
app = marimo.App(width="full")


@app.cell(hide_code=True)
def _():
    import json
    from pathlib import Path

    import marimo as mo
    import pandas as pd

    return Path, json, mo, pd


@app.cell(hide_code=True)
def _(Path, json, mo, pd):
    project_root = Path(__file__).resolve().parents[1]
    analysis_out = project_root / "analysis" / "final_v1" / "out"
    figure_dir = project_root / "outputs" / "figures" / "final_v1"
    table_dir = project_root / "outputs" / "tables" / "final_v1"

    validation_path = analysis_out / "validation_report.json"
    descriptive_path = analysis_out / "descriptive_results.json"
    sensitivity_path = analysis_out / "sensitivity_bounds.csv"
    annual_path = analysis_out / "annual_af_use_adoption.csv"
    domain_path = analysis_out / "domain_af_use_adoption.csv"

    required = {
        "Validation report": validation_path,
        "Descriptive manifest": descriptive_path,
        "Sensitivity table": sensitivity_path,
        "Annual table": annual_path,
        "Domain table": domain_path,
    }
    status = pd.DataFrame(
        [
            {
                "artifact": label,
                "present": path.is_file(),
                "path": str(path.relative_to(project_root)),
            }
            for label, path in required.items()
        ]
    )

    if validation_path.is_file():
        validation = json.loads(validation_path.read_text(encoding="utf-8"))
        readiness = "READY" if validation.get("ready_for_descriptive_analysis") else "BLOCKED"
        blockers = validation.get("blockers", [])
        warnings = validation.get("warnings", [])
    else:
        readiness = "NOT RUN"
        blockers = ["Run analysis/final_v1/prepare.py and validate.py first."]
        warnings = []

    sections = [
        mo.md(
            f"""
            # AlphaFold final-database analysis v1

            This notebook is a read-only browser for outputs generated by `analysis/final_v1/`.
            It does not rebuild the database and does not replace the frozen analysis scripts.

            **Validation status:** `{readiness}`  
            **Blockers:** {len(blockers)}  
            **Warnings:** {len(warnings)}
            """
        ),
        mo.ui.table(status, pagination=False),
    ]

    if blockers:
        sections.append(mo.md("## Blockers\n\n" + "\n".join(f"- {item}" for item in blockers)))
    if warnings:
        sections.append(mo.md("## Warnings\n\n" + "\n".join(f"- {item}" for item in warnings)))
    if sensitivity_path.is_file():
        sections.extend(
            [
                mo.md("## AF use and adoption sensitivity bounds"),
                mo.ui.table(pd.read_csv(sensitivity_path), pagination=False),
            ]
        )
    if annual_path.is_file():
        sections.extend(
            [
                mo.md("## Annual distribution, 2019–2025"),
                mo.ui.table(pd.read_csv(annual_path), pagination=False),
            ]
        )
    if domain_path.is_file():
        sections.extend(
            [
                mo.md("## Fractionally counted domain summary"),
                mo.ui.table(pd.read_csv(domain_path), pagination=True, page_size=20),
            ]
        )

    figure_links = [
        path for path in sorted(figure_dir.glob("*.pdf")) if path.is_file()
    ] if figure_dir.is_dir() else []
    if figure_links:
        sections.append(
            mo.md(
                "## Generated figures\n\n"
                + "\n".join(
                    f"- [{path.name}]({path.as_uri()})" for path in figure_links
                )
            )
        )
    table_links = [
        path for path in sorted(table_dir.glob("*.tex")) if path.is_file()
    ] if table_dir.is_dir() else []
    if table_links:
        sections.append(
            mo.md(
                "## Generated LaTeX tables\n\n"
                + "\n".join(
                    f"- [{path.name}]({path.as_uri()})" for path in table_links
                )
            )
        )

    mo.vstack(sections, gap=1.2)
    return


if __name__ == "__main__":
    app.run()
